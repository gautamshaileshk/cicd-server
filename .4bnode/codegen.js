// src/middleware/errorHandler.js — central 404 + error handler.
export function buildErrorHandlerFile() {
  return `// Central error handling. Register AFTER all routes:
//   app.use(notFound);
//   app.use(errorHandler);
export function notFound(req, res, next) {
  res.status(404).json({ message: \`Not found - \${req.originalUrl}\` });
}

export function errorHandler(err, req, res, next) {
  const status = err.status || err.statusCode || 500;
  console.error(err);
  const isProd = process.env.NODE_ENV === 'production';
  // In production, only surface messages for client (4xx) errors or errors
  // explicitly marked safe (err.expose). Never leak raw 5xx internals — a Mongo
  // E11000 or driver message discloses schema/indexes and enables enumeration.
  const showMessage = !isProd || err.expose === true || (status >= 400 && status < 500);
  res.status(status).json({
    message: showMessage ? (err.message || 'Server error') : 'Server error',
    ...(isProd ? {} : { stack: err.stack }),
  });
}
`;
}

// src/middleware/roles.js — role-based access control (RBAC).
export function buildRolesGuardFile() {
  return `// Role-based access control. Use AFTER the JWT auth middleware so req.user is set:
//   router.get('/admin', auth, roles('admin'), handler);
// Requires the login token payload to include a \`role\` (e.g. jwt.sign({ id, role })).
const roles = (...allowed) => (req, res, next) => {
  if (!req.user) {
    return res.status(401).json({ message: 'Not authenticated' });
  }
  if (allowed.length && !allowed.includes(req.user.role)) {
    return res.status(403).json({ message: 'Forbidden: insufficient role' });
  }
  next();
};

export default roles;
`;
}

// src/middleware/auth.js — JWT verification. Reads a Bearer token, verifies it
// with JWT_SECRET, and sets req.user. Use as middleware: router.get('/', auth, h).
export function buildAuthMiddleware() {
  return `import jwt from 'jsonwebtoken';

const auth = (req, res, next) => {
  const token = req.header('Authorization')?.replace('Bearer ', '');
  if (!token) {
    return res.status(401).json({ message: 'No token, authorization denied' });
  }
  try {
    // Pin the algorithm so a token can't be forged via alg-confusion (e.g. an
    // attacker signing HS256 with a public key if RS256 is ever introduced).
    const decoded = jwt.verify(token, process.env.JWT_SECRET, { algorithms: ['HS256'] });
    if (decoded.type && decoded.type !== 'access') {
      return res.status(401).json({ message: 'Token is not valid' });
    }
    req.user = decoded;
    next();
  } catch (err) {
    res.status(401).json({ message: 'Token is not valid' });
  }
};

export default auth;
`;
}

// src/middleware/validate.js — Zod request validation middleware.
export function buildValidateFile() {
  return `import { ZodError } from 'zod';

// Validate part of the request against a Zod schema. Replaces req[source] with the
// parsed/coerced data on success. Use as middleware:
//   router.post('/', validate(userSchema), handler);          // validates req.body
//   router.get('/', validate(querySchema, 'query'), handler); // validates req.query
const validate = (schema, source = 'body') => (req, res, next) => {
  const result = schema.safeParse(req[source]);
  if (!result.success) {
    const errors = (result.error instanceof ZodError ? result.error.issues : []).map((i) => ({
      path: i.path.join('.'),
      message: i.message,
    }));
    return res.status(400).json({ message: 'Validation failed', errors });
  }
  req[source] = result.data;
  next();
};

export default validate;
`;
}

// Map a Mongoose-style field descriptor to a Zod expression (no trailing optionality).
function zodForField(field) {
  const t = field.type || "String";
  switch (t) {
    case "Number":
      return "z.coerce.number()";
    case "Boolean":
      return "z.coerce.boolean()";
    case "Date":
      return "z.coerce.date()";
    case "ObjectId":
      return "z.string().regex(/^[0-9a-fA-F]{24}$/, 'Invalid id')";
    case "Array":
      return "z.array(z.any())";
    case "Buffer":
    case "Mixed":
      return "z.any()";
    case "String":
    default:
      return "z.string()";
  }
}

// src/validators/<name>.js — a Zod schema derived from a model's fields.
export function buildZodSchemaFile(name, fields) {
  const camel = toCamelCase(name);
  const lines = fields.map((f) => {
    let expr = zodForField(f);
    if (!f.required) expr += ".optional()";
    return `  ${f.name}: ${expr},`;
  });
  return `import { z } from 'zod';

export const ${camel}Schema = z.object({
${lines.join("\n")}
});

export default ${camel}Schema;
`;
}

// Parse a Zod validator's source into a { fieldName: isRequired } map for the
// top-level fields of its `z.object({ ... })`. A field is "required" for the API
// when its Zod chain has no `.optional()`/`.nullish()` — i.e. the request is
// rejected without it. This is the right source of truth for OpenAPI `required`,
// because the validator (not the Mongoose model) is what actually gates a request:
// a field can be optional in the DB schema yet required by the API, or vice versa.
// Returns null if no `z.object({...})` is found (caller should fall back to the model).
export function requiredFieldsFromZod(src) {
  if (!src || typeof src !== "string") return null;
  const objIdx = src.indexOf("z.object(");
  if (objIdx === -1) return null;
  const braceStart = src.indexOf("{", objIdx);
  if (braceStart === -1) return null;
  // Walk balanced brackets so nested objects/arrays/calls don't end the block early.
  let depth = 0;
  let end = -1;
  for (let i = braceStart; i < src.length; i++) {
    const c = src[i];
    if (c === "{" || c === "(" || c === "[") depth++;
    else if (c === "}" || c === ")" || c === "]") {
      depth--;
      if (depth === 0 && c === "}") { end = i; break; }
    }
  }
  if (end === -1) return null;
  const inner = src.slice(braceStart + 1, end);
  const map = {};
  const flush = (entry) => {
    const colon = entry.indexOf(":");
    if (colon === -1) return;
    const key = entry.slice(0, colon).trim().replace(/^['"]|['"]$/g, "");
    if (!/^[A-Za-z_$][\w$]*$/.test(key)) return;
    const expr = entry.slice(colon + 1);
    // .nullable() still requires the key (value may be null), so it doesn't count.
    map[key] = !/\.(optional|nullish)\s*\(\s*\)/.test(expr);
  };
  // Split top-level "key: expr" entries on depth-0 commas.
  let d = 0;
  let cur = "";
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i];
    if (c === "{" || c === "(" || c === "[") d++;
    else if (c === "}" || c === ")" || c === "]") d--;
    if (c === "," && d === 0) { flush(cur); cur = ""; }
    else cur += c;
  }
  if (cur.trim()) flush(cur);
  return Object.keys(map).length ? map : null;
}

// Wire `validate(<model>Schema)` into the write endpoints of a route file, and add
// the two needed imports. POST/PUT use the full schema; PATCH uses
// `<schema>.partial()` so partial updates aren't forced to send every required
// field. GET/DELETE are left alone (no body). Idempotent: skips endpoints that
// already have a validate(...) middleware. `modelBase` is the validator file base
// name (e.g. "user" → ../validators/user.js, userSchema). Returns the content
// unchanged when there are no write endpoints to wire.
export function wireValidateIntoRouteContent(content, modelBase) {
  const schemaVar = toCamelCase(modelBase) + "Schema";
  // Capture: (router.<method>('/...', <any existing middleware>, )(method)(handler arrow)
  const handlerRe =
    /(router\.(post|put|patch)\([^\n]*?,\s*)((?:async\s*)?\(\s*req\s*,\s*res\s*(?:,\s*next\s*)?\)\s*=>)/g;
  let changed = false;
  const replaced = content.replace(handlerRe, (full, head, method, handler) => {
    if (head.includes("validate(")) return full; // already guarded
    const expr = method === "patch" ? `${schemaVar}.partial()` : schemaVar;
    changed = true;
    return `${head}validate(${expr}), ${handler}`;
  });
  if (!changed) return content;
  let out = addImportToContent(replaced, `import validate from '../middleware/validate.js';`);
  out = addImportToContent(out, `import { ${schemaVar} } from '../validators/${modelBase}.js';`);
  return out;
}

// Protect a whole route file with JWT: insert `auth` as the FIRST middleware on
// every endpoint (so it runs before validation), and add the import. Idempotent.
export function wireAuthIntoRouteContent(content) {
  // (router.<method>('/path', )(existing middleware)(handler arrow)
  const handlerRe =
    /(router\.(?:get|post|put|patch|delete)\(\s*['"`][^'"`]*['"`]\s*,\s*)([\s\S]*?)((?:async\s*)?\(\s*req\s*,\s*res\s*(?:,\s*next\s*)?\)\s*=>)/g;
  let changed = false;
  const replaced = content.replace(handlerRe, (full, pathPart, middleware, handler) => {
    if (/\bauth\s*,/.test(middleware)) return full; // already protected
    changed = true;
    return `${pathPart}auth, ${middleware}${handler}`;
  });
  if (!changed) return content;
  return addImportToContent(replaced, "import auth from '../middleware/auth.js';");
}

// Anchor comment that marks the central error handler in index.js. Route
// registration looks for this so new routes are always inserted ABOVE it.
export const ERROR_HANDLER_MARKER = "// ── Error handling (must be last) ──";

// Index.js wiring plan for the selected app-level protections. Returns the imports
// to add and the code blocks to insert before routes / before the listen call.
// `features` is a set of: 'helmet', 'rateLimit', 'errorHandler'.
export function securityWiring(features) {
  const has = (f) => features.includes(f);
  const imports = [];
  const beforeRoutesParts = [];
  let beforeListen = "";

  if (has("helmet")) {
    imports.push("import helmet from 'helmet';");
    beforeRoutesParts.push(
      `// ── Security headers ──
// helmet() defaults to a strict Content-Security-Policy (script-src 'self',
// etc.) that blocks CDN-loaded scripts, inline <script> blocks, and cross-origin
// assets. We widen the policy so a typical frontend/docs page works while keeping
// the rest of helmet's protections. Tighten these directives for production.
app.use(helmet({
  contentSecurityPolicy: {
    directives: {
      defaultSrc: ["'self'"],
      scriptSrc: ["'self'", 'https:', "'unsafe-inline'"],
      styleSrc: ["'self'", 'https:', "'unsafe-inline'"],
      imgSrc: ["'self'", 'data:', 'https:'],
      connectSrc: ["'self'"],
    },
  },
  crossOriginEmbedderPolicy: false,
  // Allow other origins (e.g. a separate frontend host) to load assets served
  // by this app. Default is 'same-origin'. Tighten to 'same-site' for production.
  crossOriginResourcePolicy: { policy: 'cross-origin' },
}));`
    );
  }
  if (has("rateLimit")) {
    imports.push("import rateLimit from 'express-rate-limit';");
    beforeRoutesParts.push(
      `// ── Rate limiting ──
// Generous global cap — high enough that real frontends (which fire many calls
// per page) never notice, low enough to stop scraping/abuse at scale.
// Window + cap are read from .env (RATE_LIMIT_WINDOW_MS / RATE_LIMIT_MAX) so the
// dashboard's Security page can tune them; fall back to 15 min / 500 requests.
const apiLimiter = rateLimit({
  windowMs: Number(process.env.RATE_LIMIT_WINDOW_MS) || 15 * 60 * 1000,
  max: Number(process.env.RATE_LIMIT_MAX) || 500,
  standardHeaders: true,
  legacyHeaders: false,
});
// Strict cap for authentication routes — defends against password brute-forcing.
// Point this at your real auth routes (login / signup / password-reset).
const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 10,                  // 10 attempts per IP per window
  standardHeaders: true,
  legacyHeaders: false,
});
// Throttle everywhere EXCEPT explicit local development. Defaulting to on means a
// deploy that forgets to set NODE_ENV=production is still protected (an unset
// NODE_ENV must never mean "no rate limiting" — that was the /_dev breach posture).
if (process.env.NODE_ENV !== 'development') {
  app.use('/api/auth', authLimiter); // strict limiter first, on auth routes
  app.use(apiLimiter);               // generous global limiter for everything else
}`
    );
  }
  if (has("errorHandler")) {
    imports.push(
      "import { notFound, errorHandler } from './src/middleware/errorHandler.js';"
    );
    beforeListen = `${ERROR_HANDLER_MARKER}\napp.use(notFound);\napp.use(errorHandler);`;
  }

  return { imports, beforeRoutes: beforeRoutesParts.join("\n\n"), beforeListen };
}

// ── Pure index.js string transforms ─────────────────────────────────────────
// Used by both the CLI (lib/indexFile.js) and the in-project dashboard
// (dev-api.js) so the insertion logic lives in exactly one place.

// Add an import line after the last existing import. Idempotent.
export function addImportAfterLastImport(content, importLine) {
  const line = importLine.trim();
  if (content.includes(line)) return content;
  const lines = content.split("\n");
  let lastImportIdx = -1;
  lines.forEach((l, i) => {
    if (l.startsWith("import ")) lastImportIdx = i;
  });
  lines.splice(lastImportIdx + 1, 0, line);
  return lines.join("\n");
}

// Insert a code block just before the server starts listening. If the central
// error handler is present its marker takes precedence (new code stays above it,
// the handler stays last). Otherwise anchor on the listen/start CALL — matched by
// .index so the bare token inside `async function startServer(...)` is never hit.
export function insertBeforeListenContent(content, codeBlock) {
  const block = codeBlock.trim();
  const markerIdx = content.indexOf(ERROR_HANDLER_MARKER);
  let at;
  if (markerIdx !== -1) {
    at = markerIdx;
  } else {
    const m =
      content.match(/(app|server)\.listen\(port/) || content.match(/^startServer\(/m);
    if (!m) return content + "\n" + block + "\n";
    at = m.index;
  }
  return content.slice(0, at) + block + "\n\n" + content.slice(at);
}

// Insert app-level middleware (e.g. helmet) ahead of the route/start section so it
// wraps all subsequently-registered routes.
export function insertBeforeRoutesContent(content, codeBlock) {
  const block = codeBlock.trim();
  const markers = ["// ── Start Server", "// ── Helpers", "\nstartServer("];
  let idx = -1;
  for (const marker of markers) {
    idx = content.indexOf(marker);
    if (idx !== -1) break;
  }
  if (idx === -1) {
    const m = content.match(/^startServer\(/m);
    idx = m ? m.index : content.length;
  }
  return content.slice(0, idx) + block + "\n\n" + content.slice(idx);
}

