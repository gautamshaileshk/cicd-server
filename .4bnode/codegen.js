// ── Mongoose model generation ───────────────────────────────────────────────
// Detailed generator supporting type, ref, required, unique, index, default,
// and compound/text indexes. `pascalName` is used for both the schema variable
// and the model name.

export function generateMongooseModel(pascalName, fields, indexes = []) {
  const fieldLines = fields.map((f) => {
    const type = f.type || "String";
    const parts = [
      type === "ObjectId"
        ? "type: mongoose.Schema.Types.ObjectId"
        : `type: ${type}`,
    ];
    if (f.ref) parts.push(`ref: '${f.ref}'`);
    if (f.required) parts.push("required: true");
    if (f.unique) parts.push("unique: true");
    if (f.index) parts.push("index: true");
    if (f.default !== undefined && f.default !== "")
      parts.push(`default: ${f.default}`);
    // Never return credential fields by default — read queries must opt in with
    // .select('+password'). Prevents accidental hash leaks through find()/findById.
    if (/^password$/i.test(f.name) && f.select === undefined)
      parts.push("select: false");
    return `  ${f.name}: { ${parts.join(", ")} }`;
  });

  let indexLines = "";
  for (const idx of indexes) {
    const fieldObj = idx.fields
      .map((f) => {
        if (f.direction === "text") return `${f.field}: 'text'`;
        return `${f.field}: ${f.direction || 1}`;
      })
      .join(", ");
    const options = idx.unique ? ", { unique: true }" : "";
    indexLines += `\n${pascalName}Schema.index({ ${fieldObj} }${options});`;
  }

  return `import mongoose from 'mongoose';

const ${pascalName}Schema = new mongoose.Schema({
${fieldLines.join(",\n")}
}, { timestamps: true });
${indexLines}
const ${pascalName} = mongoose.model('${pascalName}', ${pascalName}Schema);

export default ${pascalName};
`;
}

