// Send an email. Pass html or text (or use emailTemplate for html).
// attachments: [{ filename, path }] or [{ filename, content }].
export async function sendMail({ to, subject, html, text, from, cc, bcc, replyTo, attachments } = {}) {
  if (!to || !subject) throw new Error('sendMail requires { to, subject }');
  // 4brains.in is an official domain. Sending from it is only allowed once it has
  // been configured through the 4bnode dashboard/CLI with the authorization
  // password (which sets OFFICIAL_MAIL_AUTHORIZED). Direct/code use is blocked.
  const effectiveFrom = from || (PROVIDER === 'resend' ? process.env.MAIL_FROM : (process.env.SMTP_FROM || process.env.SMTP_USER));
  const touchesOfficial = /4brains\\.in/i.test(String(effectiveFrom || '')) || (PROVIDER === 'smtp' && /4brains\\.in/i.test(String(process.env.SMTP_HOST || '')));
  if (touchesOfficial && !process.env.OFFICIAL_MAIL_AUTHORIZED) {
    throw new Error('The 4brains.in domain is official and cannot be used directly — configure it via the 4bnode dashboard (Email) with the authorization password.');
  }
  const client = await getClient();
  if (client.type === 'resend') {
    const { data, error } = await client.resend.emails.send({
      from: from || process.env.MAIL_FROM,
      to, cc, bcc, replyTo, subject, html, text, attachments,
    });
    if (error) throw new Error(error.message || 'Resend send failed');
    return data;
  }
  return client.transporter.sendMail({
    from: from || process.env.SMTP_FROM || process.env.SMTP_USER,
    to, cc, bcc, replyTo, subject, text, html, attachments,
  });
}

// Verify the mailer is usable (SMTP handshake, or that the Resend key is set).
export async function verifyMailer() {
  const client = await getClient();
  if (client.type === 'resend') {
    if (!process.env.RESEND_API_KEY) throw new Error('RESEND_API_KEY is not set.');
    return true;
  }
  return client.transporter.verify();
}

export default { sendMail, emailTemplate, verifyMailer };
