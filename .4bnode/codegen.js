export function buildDocsRouter() {
  return `import express from 'express';
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const router = express.Router();
const DIR = path.dirname(fileURLToPath(import.meta.url));
const SPEC = path.join(DIR, 'openapi.json');
const AUTH = path.join(DIR, 'docs-auth.json');

// Optional password protection. If src/docs-auth.json holds { hash, secret }, the
// whole /docs surface requires a single password (NO username) via a small login
// page + a signed session cookie. Set/remove the password from the dashboard
// (API Docs). Read live (mtime-cached), so changes apply without a restart.
let _authCache = { mtimeMs: -1, hash: null, secret: null };
function docsAuth() {
  try {
    const { mtimeMs } = fs.statSync(AUTH);
    if (mtimeMs !== _authCache.mtimeMs) {
      const data = JSON.parse(fs.readFileSync(AUTH, 'utf8'));
      _authCache = { mtimeMs, hash: (data && data.hash) || null, secret: (data && data.secret) || null };
    }
  } catch { _authCache = { mtimeMs: -1, hash: null, secret: null }; }
  return _authCache;
}
// Stable server secret for signing session cookies. Prefers the persisted secret;
// falls back to an ephemeral random one (legacy files with no secret) so a leaked
// docs-auth.json can never be forged into a valid session.
const EPHEMERAL_SECRET = crypto.randomBytes(32).toString('hex');
function sessionSecret() { return docsAuth().secret || EPHEMERAL_SECRET; }
function safeEq(a, b) {
  try { const x = Buffer.from(String(a)), y = Buffer.from(String(b)); return x.length === y.length && crypto.timingSafeEqual(x, y); } catch { return false; }
}
// Verify a submitted password against the stored hash: salted scrypt
// (scrypt$salt$hash) or legacy unsalted sha256 (back-compat).
function verifyPassword(candidate, hash) {
  if (!candidate || !hash) return false;
  try {
    if (hash.startsWith('scrypt$')) {
      const [, saltHex, hashHex] = hash.split('$');
      const expected = Buffer.from(hashHex, 'hex');
      const actual = crypto.scryptSync(String(candidate), Buffer.from(saltHex, 'hex'), expected.length);
      return expected.length === actual.length && crypto.timingSafeEqual(expected, actual);
    }
    return safeEq(crypto.createHash('sha256').update(String(candidate)).digest('hex'), hash);
  } catch { return false; }
}
// Session cookie = base64url(payload).hmac. The stored hash is NEVER sent to the
// client, so a leaked docs-auth.json can't be replayed as a session.
function signSession() {
  const payload = Buffer.from(JSON.stringify({ exp: Date.now() + 86400000 })).toString('base64url');
  const sig = crypto.createHmac('sha256', sessionSecret()).update(payload).digest('base64url');
  return payload + '.' + sig;
}
function validSession(token) {
  if (!token || typeof token !== 'string' || token.indexOf('.') === -1) return false;
  const [payload, sig] = token.split('.');
  const expect = crypto.createHmac('sha256', sessionSecret()).update(payload).digest('base64url');
  if (!safeEq(sig, expect)) return false;
  try { const { exp } = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8')); return typeof exp === 'number' && exp > Date.now(); } catch { return false; }
}
function cookieToken(req) {
  const m = (req.headers.cookie || '').match(/(?:^|; )docs_auth=([^;]+)/);
  return m ? decodeURIComponent(m[1]) : null;
}
const LOGIN_HTML = ${JSON.stringify(buildDocsLoginHtml())};

// Password submit — reachable without auth.
router.post('/login', (req, res) => {
  const { hash } = docsAuth();
  if (!hash) return res.redirect('/docs');
  if (verifyPassword(String((req.body && req.body.password) || ''), hash)) {
    const secure = process.env.NODE_ENV === 'production' ? '; Secure' : '';
    res.setHeader('Set-Cookie', 'docs_auth=' + signSession() + '; Path=/docs; HttpOnly; SameSite=Lax; Max-Age=86400' + secure);
    return res.redirect('/docs');
  }
  return res.status(401).type('html').send(LOGIN_HTML.replace('<!--ERR-->', 'Incorrect password'));
});

// Gate the rest of /docs behind the password (when one is set).
router.use((req, res, next) => {
  const { hash } = docsAuth();
  if (!hash) return next();                            // no password → open
  if (validSession(cookieToken(req))) return next();
  return res.status(401).type('html').send(LOGIN_HTML);
});

// Interactive API documentation. The page is fully self-contained (no external
// CDN); the spec is generated by 4bnode and served from this app.
router.get('/openapi.json', (req, res) => {
  res.set('Cache-Control', 'no-store');
  if (!fs.existsSync(SPEC)) return res.status(404).json({ error: 'API spec not generated yet.' });
  res.sendFile(SPEC);
});

const DOCS_PAGE = ${JSON.stringify(buildDocsHtml("/docs/openapi.json"))};

router.get('/', (req, res) => {
  // Inline the spec into the page so a password-protected page doesn't need a
  // second authenticated request (some browsers won't attach the docs cookie to
  // the fetch). Falls back to fetching /openapi.json if no spec is inlined.
  let spec = 'null';
  try {
    if (fs.existsSync(SPEC)) {
      const raw = fs.readFileSync(SPEC, 'utf8').trim();
      // Escape '<' so a spec value containing '</script>' can't break out of the
      // inline <script>. The '\\u003c' sequence still evaluates to '<' in JS.
      if (raw) spec = raw.split('<').join(String.fromCharCode(92) + 'u003c');
    }
  } catch {}
  // Never cache the docs page — keeps it from going stale after a regenerate.
  res.set('Cache-Control', 'no-store');
  res.type('html').send(DOCS_PAGE.replace('/*__SPEC__*/null', () => spec));
});

export default router;
`;
}

