// Field names that must never be mass-assigned from a request body — privilege
// flags and prototype-pollution keys. Excluded from generated create/update DTOs
// by default; set these server-side (e.g. in an admin route) instead.
export const MASS_ASSIGN_BLOCKED = new Set([
  "role", "roles", "isadmin", "admin", "isadministrator",
  "verified", "isverified", "permissions", "scopes",
  "__proto__", "constructor", "prototype",
]);
function writableFields(fields) {
  return fields.filter((f) => !MASS_ASSIGN_BLOCKED.has(String(f).toLowerCase()));
}

export function buildInsertCode(pascalName, fields, dataSource) {
  fields = writableFields(fields);
  const assignments = fields
    .map((f) => `    ${f}: ${dataSource}.${f}`)
    .join(",\n");

  let passwordLogic = "";
  if (fields.includes("password")) {
    passwordLogic = `
  if (newData.password) {
    const salt = await bcrypt.genSalt(10);
    newData.password = await bcrypt.hash(newData.password, salt);
  }`;
  }

  return `
router.post('/create', async (req, res) => {
  const newData = {
${assignments}
  };
${passwordLogic}
  try {
    const newDocument = new ${pascalName}(newData);
    await newDocument.save();
    res.json({ message: 'Data inserted successfully', data: newDocument });
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: 'Server error' });
  }
});`;
}

