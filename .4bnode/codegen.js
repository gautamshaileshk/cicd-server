// API Documentation — OpenAPI 3 spec + Swagger UI (served at /docs).
// Reuses extractRequestFields output (endpoints) and model field metadata.
// ─────────────────────────────────────────────────────────────────────────────
function openApiType(t) {
  switch (t) {
    case "Number":
    case "Int": return { type: "integer" };
    case "Float": return { type: "number" };
    case "Boolean": return { type: "boolean" };
    case "Date":
    case "DateTime": return { type: "string", format: "date-time" };
    case "ObjectId": return { type: "string" };
    case "Array": return { type: "array", items: {} };
    case "Buffer": return { type: "string", format: "binary" };
    case "Json":
    case "Mixed": return { type: "object" };
    case "String":
    default: return { type: "string" };
  }
}

// Build an OpenAPI 3.0 document from parsed endpoints + models.
// endpoints: [{ method, path, fullPath, bodyFields[], queryFields[], params[], fileFields[], hasAuth }]
// models: [{ name, fields:[{name,type,required}] }]
export function buildOpenApiSpec({ title = "API", version = "1.0.0", endpoints = [], models = [] } = {}) {
  const paths = {};
  for (const ep of endpoints) {
    const raw = ep.fullPath || ep.path || "/";
    const oaPath = raw.replace(/:(\w+)/g, "{$1}");
    const method = (ep.method || "GET").toLowerCase();
    paths[oaPath] = paths[oaPath] || {};
    const op = { summary: `${ep.method} ${raw}`, responses: { "200": { description: "Success" } } };

    const parameters = [];
    (ep.params || []).forEach((p) => parameters.push({ name: p, in: "path", required: true, schema: { type: "string" } }));
    (ep.queryFields || []).forEach((f) => parameters.push({ name: f.name, in: "query", required: false, schema: openApiType(f.type) }));
    if (parameters.length) op.parameters = parameters;

    const bodyFields = ep.bodyFields || [];
    const fileFields = ep.fileFields || [];
    if (["post", "put", "patch"].includes(method) && (bodyFields.length || fileFields.length)) {
      const properties = {};
      const required = [];
      bodyFields.forEach((f) => { properties[f.name] = openApiType(f.type); if (f.required) required.push(f.name); });
      // Uploaded files are required by default (an upload endpoint exists to receive
      // the file). A file field can opt out with required:false.
      fileFields.forEach((f) => { properties[f.name] = { type: "string", format: "binary" }; if (f.required !== false) required.push(f.name); });
      const schema = { type: "object", properties };
      if (required.length) schema.required = required;
      const mime = fileFields.length ? "multipart/form-data" : "application/json";
      op.requestBody = { content: { [mime]: { schema } } };
    }
    if (ep.hasAuth) op.security = [{ bearerAuth: [] }];
    paths[oaPath][method] = op;
  }

  const schemas = {};
  for (const m of models) {
    const properties = {};
    (m.fields || []).forEach((f) => { properties[f.name] = openApiType(f.type); });
    schemas[toPascalCase(m.name)] = { type: "object", properties };
  }

  const components = { securitySchemes: { bearerAuth: { type: "http", scheme: "bearer", bearerFormat: "JWT" } } };
  if (Object.keys(schemas).length) components.schemas = schemas;

  return { openapi: "3.0.0", info: { title, version }, servers: [{ url: "/" }], paths, components };
}

