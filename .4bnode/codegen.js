// ── Name helpers ────────────────────────────────────────────────────────────

export function toCamelCase(str) {
  return str.replace(/-([a-z])/g, (g) => g[1].toUpperCase());
}

export function toPascalCase(str) {
  const camel = toCamelCase(str);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

export function sanitizeName(input) {
  if (!input || typeof input !== "string") {
    throw new Error("Name is required.");
  }
  const trimmed = input.trim();
  if (!/^[a-zA-Z][a-zA-Z0-9_-]*$/.test(trimmed)) {
    throw new Error(
      `Invalid name "${trimmed}". Use only letters, numbers, hyphens, and underscores. Must start with a letter.`
    );
  }
  return trimmed;
}

// Validate a model/route FIELD name before it is interpolated into generated code.
// A field name becomes a JS identifier (destructuring, object keys), so anything
// but a plain identifier could break out of the template or pollute a prototype.
export function sanitizeFieldName(input) {
  if (!input || typeof input !== "string") {
    throw new Error("Field name is required.");
  }
  const trimmed = input.trim();
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(trimmed)) {
    throw new Error(
      `Invalid field name "${trimmed}". Use letters, numbers, and underscores; start with a letter or underscore.`
    );
  }
  if (trimmed === "__proto__" || trimmed === "constructor" || trimmed === "prototype") {
    throw new Error(`Field name "${trimmed}" is reserved.`);
  }
  return trimmed;
}

// ── Pure string helpers for route files ─────────────────────────────────────
// These operate on file CONTENT (a string) and return new content. The
// file-reading/writing wrappers live in lib/routeFile.js (CLI) and inline in
// dev-api.js (dashboard); both delegate here so the insertion logic is shared.

export function addImportToContent(content, importStatement) {
  const stmt = importStatement.trim();
  if (content.includes(stmt)) return content;
  return stmt + "\n" + content;
}

export function insertCodeIntoContent(content, codeBlock) {
  const block = codeBlock.trim();

  // Prefer inserting before "export default router;" — most reliable anchor.
  const exportIndex = content.lastIndexOf("export default router;");
  if (exportIndex !== -1) {
    return (
      content.slice(0, exportIndex) +
      block +
      "\n\n" +
      content.slice(exportIndex)
    );
  }

  // Fallback: before the last "});".
  const lastClose = content.lastIndexOf("});");
  if (lastClose !== -1) {
    return content.slice(0, lastClose) + block + "\n" + content.slice(lastClose);
  }

  return content + "\n" + block + "\n";
}

