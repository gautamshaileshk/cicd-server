// Add packages to package.json (dependencies, or devDependencies when dev:true).
// Pure: takes the file CONTENT, returns { content, changed }. Skips names already
// present in either deps or devDeps. Unknown packages fall back to "latest".
export function addDepsToPackageJson(content, names, { dev = false } = {}) {
  const pkg = JSON.parse(content);
  const key = dev ? "devDependencies" : "dependencies";
  pkg[key] = pkg[key] || {};
  let changed = false;
  for (const name of names) {
    const inDeps = pkg.dependencies && pkg.dependencies[name];
    const inDev = pkg.devDependencies && pkg.devDependencies[name];
    if (!inDeps && !inDev) {
      pkg[key][name] = PACKAGE_VERSIONS[name] || "latest";
      changed = true;
    }
  }
  return { content: JSON.stringify(pkg, null, 2) + "\n", changed };
}

// ─────────────────────────────────────────────────────────────────────────────
// Request-field detection — used by the API Tester to auto-fill keys from a route.
// Handles BOTH destructuring (`const { a, b } = req.body`) AND direct member access
// (`req.body.a`, `req.body['a']`), since generated CRUD routes use the latter.
// ─────────────────────────────────────────────────────────────────────────────
export function extractRequestFields(handlerBody, source = "body") {
  const src = source === "query" ? "query" : "body";
  const names = [];
  const seen = new Set();
  const add = (raw) => {
    const n = (raw || "").trim();
    if (n && /^[A-Za-z_$][\w$]*$/.test(n) && !seen.has(n)) {
      seen.add(n);
      names.push(n);
    }
  };
  const body = handlerBody || "";
  // const { a, b: x } = req.<src>  → take the key before any ':'
  const destructure = body.match(new RegExp(`const\\s*\\{\\s*([^}]+)\\}\\s*=\\s*req\\.${src}`));
  if (destructure) destructure[1].split(",").forEach((f) => add(f.split(":")[0]));
  // req.<src>.field
  const dot = new RegExp(`req\\.${src}\\.(\\w+)`, "g");
  let m;
  while ((m = dot.exec(body)) !== null) add(m[1]);
  // req.<src>['field'] / req.<src>["field"]
  const bracket = new RegExp(`req\\.${src}\\[\\s*['"](\\w+)['"]\\s*\\]`, "g");
  while ((m = bracket.exec(body)) !== null) add(m[1]);
  return names;
}

// Detect multer upload fields in a route handler so the OpenAPI builder can mark
// the body as multipart/form-data with the right file fields. Handles:
//   upload.single('avatar')                        -> [{name:'avatar'}]
//   upload.array('photos', 5)                      -> [{name:'photos'}]
//   upload.fields([{ name: 'a' }, { name: 'b' }])  -> [{name:'a'},{name:'b'}]
export function extractFileFields(handlerBody) {
  const body = handlerBody || "";
  const out = [];
  const seen = new Set();
  const add = (name) => { if (name && !seen.has(name)) { seen.add(name); out.push({ name }); } };
  (body.match(/upload\.(?:single|array)\(\s*['"]([^'"]+)['"]/g) || []).forEach((s) => {
    const m = s.match(/['"]([^'"]+)['"]/);
    if (m) add(m[1]);
  });
  const fieldsCall = body.match(/upload\.fields\(\s*\[([\s\S]*?)\]/);
  if (fieldsCall) {
    (fieldsCall[1].match(/name\s*:\s*['"]([^'"]+)['"]/g) || []).forEach((n) => {
      const m = n.match(/['"]([^'"]+)['"]/);
      if (m) add(m[1]);
    });
  }
  return out;
}

